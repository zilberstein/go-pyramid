// Reads an exported ai-hard-policy.js and plays it on the engine, exactly the
// way web/index.html does (so evaluations measure what actually ships).
import fs from 'node:fs';
import { swapKey, keepKey, numKeepActions, mediumSwap, mediumKeep } from './engine.mjs';

export function loadPolicy(path) {
  const src = fs.readFileSync(path, 'utf8');
  const m = src.match(/GO_PYRAMID_HARD_POLICY = "([^"]*)"/);
  const swap = new Map(), keep = new Map();
  if (m && m[1]) {
    for (const kv of m[1].split(',')) {
      const [k, a] = kv.slice(1).split(':');
      (kv[0] === 's' ? swap : keep).set(parseInt(k, 36), parseInt(a, 36));
    }
  }
  return { swap, keep };
}

export function hardPolicy(pol) {
  return st => {
    const s = st.toMove, me = st.p[s], op = st.p[1 - s];
    // The table is for seat 1; seat 0 sees the same features apart from the seat bit.
    const sa = pol.swap.get(swapKey(1, me, op));
    if (sa === undefined ? mediumSwap(st) : sa === 0) return 0;
    if (numKeepActions(me) === 1) return 1;
    const ka = pol.keep.get(keepKey(1, me, op));
    return 1 + (ka === undefined ? mediumKeep(st) : ka);
  };
}

// Key divisors that isolate the seat bit (see swapKey/keepKey in engine.mjs).
export const SWAP_DIV = 1024 * 1024 * 8 * 8 * 4;
export const KEEP_DIV = 1024 * 1024 * 4;

// Combine raw seat-1 tables from one or more independent DCFR runs (summing
// visit counts and average-strategy numerators), purify, and render
// ai-hard-policy.js. Only infosets with >= minVisits pooled updates whose best
// action differs from Medium are listed; everything else falls back to Medium.
export function exportPolicy(dumps, minVisits) {
  const merged = [new Map(), new Map()];
  for (const d of dumps) {
    [d.sw, d.kp].forEach((rows, i) => {
      for (const [key, n, def, S] of rows) {
        const e = merged[i].get(key);
        if (!e) merged[i].set(key, { n, def, S: S.slice() });
        else { e.n += n; S.forEach((x, a) => { e.S[a] += x; }); }
      }
    });
  }
  const parts = [];
  let trusted = 0, total = 0;
  merged.forEach((m, i) => {
    for (const [key, e] of m) {
      total++;
      if (e.n < minVisits) continue;
      trusted++;
      let best = e.def;
      e.S.forEach((x, a) => { if (x > e.S[best]) best = a; });
      if (best !== e.def) parts.push((i ? 'k' : 's') + key.toString(36) + ':' + best.toString(36));
    }
  });
  const secs = dumps.reduce((a, d) => a + d.seconds, 0);
  const trav = dumps.reduce((a, d) => a + d.traversals, 0);
  const text = `// Generated by web/cfr (train.mjs/merge.mjs): ${dumps.length} DCFR run(s), ${secs} CPU-seconds, ${trav} traversals.\n` +
    `// Purified DCFR average strategy for the computer (seat 1). "s" entries are swapKey(),\n` +
    `// "k" entries keepKey() from web/cfr/engine.mjs. Anything not listed plays like Medium.\n` +
    `window.GO_PYRAMID_HARD_POLICY = "${parts.join(',')}";\n`;
  return { text, deviations: parts.length, trusted, total };
}
